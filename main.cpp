std::uint64_t binomial(std::uint64_t n, std::uint64_t k) {
    if (k > n) return 0;
    if (k > n - k) k = n - k;          
    std::uint64_t result = 1;
    for (std::uint64_t i = 1; i <= k; ++i) {
        result = result * (n - k + i) / i;
    }
    return result;
}




