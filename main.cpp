template <typename T>
class Matrix {
    public:
        Matrix() = default;
        Matrix(std::size_t rows, std::size_t columns, const T& value) : m_(rows), n_(columns), data_(rows * columns, value) {}

        T& operator()(std::size_t i, std::size_t j) {
            assert(i < m_ && j < n_);
            return data_[i * n_ + j];
        }
        const T& operator()(std::size_t i, std::size_t j) const {
            assert(i < m_ && j < n_);
            return data_[i * n_ + j];
        }

        std::size_t rows()  const {return m_;}
        std::size_t columns() const {return n_;}

        auto begin() {return data_.begin();}
        auto end() {return data_.end();}
        auto begin() const {return data_.begin();}
        auto end() const {return data_.end();}

    private:
        std::size_t m_ = 0, n_ = 0;
        std::vector<T> data_;
};

struct KST;

struct Edge {
    bool active = true;
    std::vector<KST*> KSTs;
    
    void addKST(KST* kst);
    void removeKST(KST* kst);
};

struct KST {
    int id;
    bool alive = true;
    std::vector<Edge*> edges;
    int soloEdges = 0;

    void incSoloEdges() {soloEdges++;}
    void decSoloEdges() {soloEdges--;}
};

struct position {
    int row;
    int column;
};

inline void Edge::addKST(KST* kst) {
    KSTs.push_back(kst);
};

inline void Edge::removeKST(KST* kst) {
    auto it = std::find(KSTs.begin(), KSTs.end(), kst);
    if (it != KSTs.end()) {
        *it = KSTs.back();
        KSTs.pop_back();
    } else {
        std::cerr << "Error: KST not found in edge's KST list." << std::endl;
    }
};

//generated by AI (input: create a class that generates all K(s,t) in a bipartite graph given its adjacency matrix)
class KSTGenerator {
    public:
        KSTGenerator(Matrix<Edge>& adj, std::size_t s, std::size_t t, int firstId = 0)
            : adj_(adj), s_(s), t_(t), nextId_(firstId) {}
 
        void generate(std::vector<std::unique_ptr<KST>>& out) {
            out_ = &out;
            const std::size_t m = adj_.rows(), n = adj_.columns();
            if (s_ == 0 || t_ == 0 || s_ > m || t_ > n) return;
 
            std::vector<std::size_t> allCols(n);
            for (std::size_t c = 0; c < n; ++c) allCols[c] = c;
 
            rows_.clear();
            rows_.reserve(s_);
            cols_.clear();
            cols_.reserve(t_);
            chooseRows(0, allCols);
        }
 
        int nextId() const { return nextId_; }
 
    private:
        void chooseRows(std::size_t start, const std::vector<std::size_t>& common) {
            if (rows_.size() == s_) {
                chooseCols(common, 0);
                return;
            }
            const std::size_t m = adj_.rows();
            const std::size_t stillNeeded = s_ - rows_.size();
 
            std::vector<std::size_t> next;
            next.reserve(common.size());
 
            for (std::size_t r = start; r + stillNeeded <= m; ++r) {
                next.clear();
                for (std::size_t c : common)
                    if (adj_(r, c).active) next.push_back(c);
 
                if (next.size() < t_) continue;     // prune
 
                rows_.push_back(r);
                chooseRows(r + 1, next);
                rows_.pop_back();
            }
        }
 
        void chooseCols(const std::vector<std::size_t>& common, std::size_t start) {
            if (cols_.size() == t_) {
                emit();
                return;
            }
            const std::size_t stillNeeded = t_ - cols_.size();
            for (std::size_t i = start; i + stillNeeded <= common.size(); ++i) {
                cols_.push_back(common[i]);
                chooseCols(common, i + 1);
                cols_.pop_back();
            }
        }
 
        void emit() {
            auto kst = std::make_unique<KST>();
            kst->id = nextId_++;
            kst->edges.reserve(s_ * t_);
            for (std::size_t r : rows_) {
                for (std::size_t c : cols_) {
                    Edge* e = &adj_(r, c);
                    kst->edges.push_back(e);
                    e->addKST(kst.get());
                }
            }
            out_->push_back(std::move(kst));
        }
 
        Matrix<Edge>& adj_;
        std::size_t s_, t_;
        int nextId_;
        std::vector<std::size_t> rows_, cols_;
        std::vector<std::unique_ptr<KST>>* out_ = nullptr;
};

inline std::vector<std::unique_ptr<KST>> generateKSTs(Matrix<Edge>& adj, std::size_t s, std::size_t t, int firstId = 0){
    std::vector<std::unique_ptr<KST>> result;
 
    KSTGenerator g1(adj, s, t, firstId);
    g1.generate(result);
 
    return result;
}

struct KSTSet {
    Matrix<Edge> adj;                        
    std::vector<std::unique_ptr<KST>> ksts;   

    KSTSet() = default;
    KSTSet(int m, int n) : adj(m, n, Edge()) {}
};

inline KSTSet generateKSTs(int m, int n, int s, int t, int firstId = 0) {
    KSTSet result;
    result.adj = Matrix<Edge>(m, n, Edge());
    result.ksts = generateKSTs(result.adj, s, t, firstId);
    return result;
}



//generated by AI (input: create a graph6 representation of a bipartite graph given its adjacency matrix)
template <typename T, typename IsAdjacent>
std::string to_graph6(const Matrix<T>& M, IsAdjacent is_adjacent)
{
    const std::size_t m = M.rows();
    const std::size_t k = M.columns();
    const std::uint64_t n = static_cast<std::uint64_t>(m) + k;
 
    std::string out;
 
    // ---- N(n): vertex count ------------------------------------------------
    auto put_bits = [&out](std::uint64_t value, int nbits) {
        // big-endian groups of 6 bits, each offset by 63
        for (int shift = nbits - 6; shift >= 0; shift -= 6)
            out.push_back(static_cast<char>(((value >> shift) & 0x3F) + 63));
    };
 
    if (n <= 62) {
        out.push_back(static_cast<char>(n + 63));
    } else if (n <= 258047) {
        out.push_back(126);
        put_bits(n, 18);
    } else if (n <= 68719476735ULL) {
        out.push_back(126);
        out.push_back(126);
        put_bits(n, 36);
    } else {
        throw std::length_error("graph6: too many vertices");
    }
 
    // ---- R(x): upper triangle, column by column ---------------------------
    // Bit order: x(0,1), x(0,2), x(1,2), x(0,3), x(1,3), x(2,3), ...
    // i.e. for j = 1..n-1, for i = 0..j-1.
    const std::uint64_t total_bits = n == 0 ? 0 : n * (n - 1) / 2;
    out.reserve(out.size() + (total_bits + 5) / 6);
 
    unsigned acc = 0;   // current 6-bit group
    int filled = 0;     // bits already in acc
 
    auto push_bit = [&](bool b) {
        acc = (acc << 1) | static_cast<unsigned>(b);
        if (++filled == 6) {
            out.push_back(static_cast<char>(acc + 63));
            acc = 0;
            filled = 0;
        }
    };
 
    for (std::uint64_t j = 1; j < n; ++j) {
        if (j < m) {
            // j is in U: U-U pairs are never adjacent
            for (std::uint64_t i = 0; i < j; ++i) push_bit(false);
        } else {
            // j is in V (column c); i < m are U vertices, the rest are V
            const std::size_t c = static_cast<std::size_t>(j - m);
            for (std::uint64_t i = 0; i < j; ++i)
                push_bit(i < m && is_adjacent(M(static_cast<std::size_t>(i), c)));
        }
    }
 
    // pad the last group with zeros on the right
    if (filled > 0)
        out.push_back(static_cast<char>((acc << (6 - filled)) + 63));
 
    return out;
}

//AI generated function to find the indices of the maximum values in a vector
std::vector<int> maxIndizes(const std::vector<int>& v) {
    std::vector<int> indizes;
    if (v.empty()) return indizes;

    int maximum = v[0];
    for (std::size_t i = 0; i < v.size(); ++i) {
        if (v[i] > maximum) {
            maximum = v[i];
            indizes.clear();         
            indizes.push_back(i);
        } else if (v[i] == maximum) {
            indizes.push_back(i);     
        }
    }
    return indizes;
}

template <typename T>
std::vector<T> selectByIndices(const std::vector<T>& values, const std::vector<int>& indices) {
    std::vector<T> result;
    result.reserve(indices.size());
    for (int i : indices)
        result.push_back(values[i]);
    return result;
}

position bestCandidate(const std::vector<position>& candidates, const Matrix<Edge>& edges, int m, int n) {
    position bestC;
    int bestScore = -1;

    for (const position& c : candidates) {
        int score = edges(c.row, c.column).KSTs.size();
        if (score > bestScore) {
            bestScore = score;
            bestC = c;
        }
    }
    return bestC;
}

std::vector<position> findCandidates(Matrix<Edge>& edges, int m, int n) {
    std::vector<position> result;
    for (int i = 0; i < m; ++i) {
        for (int j = 0; j < n; ++j) {
            if (edges(i, j).active && edges(i, j).KSTs.size() > 0) {
                result.push_back({i, j});
            }
        }
    }
    return result;
}


